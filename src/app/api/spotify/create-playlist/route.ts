import { NextResponse } from "next/server";
import { getSpotifyAccessToken } from "@/lib/spotify/get-token";
import {
  getTopTracks,
  createPlaylist,
  addTracksToPlaylist,
  uploadPlaylistImage,
} from "@/lib/spotify/client";
import { fetchSeasonalImage } from "@/lib/unsplash";
import type { TimeRange } from "@/lib/spotify/types";

const VALID_RANGES: TimeRange[] = ["short_term", "medium_term", "long_term"];

function getPreviousMonth(): { name: string; year: number } {
  const now = new Date();
  const prev = new Date(now.getFullYear(), now.getMonth() - 1, 1);
  return {
    name: prev.toLocaleString("en-US", { month: "long" }),
    year: prev.getFullYear(),
  };
}

export async function POST(request: Request) {
  try {
    const token = await getSpotifyAccessToken();
    if (!token) {
      return NextResponse.json({ error: "Spotify not connected" }, { status: 401 });
    }

    let body: { timeRange?: string };
    try {
      body = await request.json();
    } catch {
      return NextResponse.json(
        { error: "Invalid JSON body" },
        { status: 400 }
      );
    }

    const timeRange = VALID_RANGES.includes(body.timeRange as TimeRange)
      ? (body.timeRange as TimeRange)
      : "short_term";

    const topTracks = await getTopTracks(token, timeRange, 50);

    const uris = topTracks.items.map((t) => t.uri).filter(Boolean);
    if (uris.length === 0) {
      return NextResponse.json(
        { error: "No tracks to add to playlist" },
        { status: 400 }
      );
    }

    const prev = getPreviousMonth();
    const playlistName = `${prev.name.toLowerCase()} ${prev.year}`;
    const playlist = await createPlaylist(
      token,
      playlistName,
      `your favorite songs from ${prev.name.toLowerCase()} — generated by monthly records`
    );

    await addTracksToPlaylist(token, playlist.id, uris);

    try {
      const base64Image = await fetchSeasonalImage(prev.name);
      if (base64Image) {
        await uploadPlaylistImage(token, playlist.id, base64Image);
      }
    } catch (imgErr) {
      console.warn("[create-playlist] Cover image failed, skipping", imgErr);
    }

    const url =
      (playlist as { external_urls?: { spotify?: string } }).external_urls?.spotify ??
      `https://open.spotify.com/playlist/${playlist.id}`;

    return NextResponse.json({
      url,
      name: playlist.name,
    });
  } catch (err) {
    console.error("[create-playlist]", err);
    const message = err instanceof Error ? err.message : "Failed to create playlist";
    return NextResponse.json(
      { error: message },
      { status: 500 }
    );
  }
}
